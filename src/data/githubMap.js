const heatBursts = new Set([2, 3, 8, 13, 14, 19, 23, 24, 25, 30, 31, 37, 43, 44, 49]);

export const heatmapWeeks = Array.from({ length: 52 }, (_, week) =>
  Array.from({ length: 7 }, (_, day) => {
    const grain = (week * 17 + day * 11 + 23) % 13;
    let value = grain < 2 ? 1 : 0;

    if (grain === 2 || (week + day) % 17 === 0) value = 2;
    if (heatBursts.has(week) && (day + week) % 2 !== 0) value = Math.max(value, 2 + ((week + day) % 3));
    if (week >= 22 && week <= 26 && [1, 2, 3, 5].includes(day)) value = 4;
    if ((week * (day + 1)) % 29 === 0 && day !== 2) value = 0;

    return Math.min(value, 4);
  }),
);
